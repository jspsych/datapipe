import { customAlphabet } from "nanoid";
import { doc, writeBatch, arrayUnion } from "firebase/firestore";
import { db, auth } from "./firebase";

export async function getUserOsfToken(user) {
  const idToken = await user.getIdToken();
  const response = await fetch("/api/getosftoken", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${idToken}`,
    },
  });

  if (!response.ok) {
    const errorText = await response.text();

    if (response.status === 400) {
      try {
        const errorData = JSON.parse(errorText);
        if (errorData.details && errorData.details.includes("invalid_request")) {
          throw new Error(
            "Your OSF authentication has expired. Please sign out of DataPipe and sign in again with OSF."
          );
        }
      } catch (parseError) {
        if (parseError instanceof SyntaxError) {
          // JSON parse failed — fall through to generic message
        } else {
          throw parseError;
        }
      }
      throw new Error(
        "Your OSF authentication has expired. Please sign out of DataPipe and sign in again with OSF."
      );
    }

    throw new Error(`Failed to get OSF token: ${response.status}`);
  }

  const data = await response.json();
  return data.token || null;
}

export async function createOsfChildComponent(osfToken, osfRepo, osfComponentName, region = 'us') {
  // Clean OSF repo URL if needed (handles both production and test environments)
  osfRepo = osfRepo.replace(/^https?:\/\/(?:test\.)?osf\.io\//, "");

  
  const osfResult = await fetch(
    `https://api.${process.env.NEXT_PUBLIC_OSF_ENV}osf.io/v2/nodes/${osfRepo}/children/?region=${region}`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${osfToken}`,
      },
      body: JSON.stringify({
        data: {
          type: "nodes",
          attributes: {
            title: osfComponentName,
            category: "data",
            description:
              "This node was automatically generated by DataPipe (https://pipe.jspsych.org/)",
          },
        },
      }),
    }
  );

  if (!osfResult.ok) {
    const errorText = await osfResult.text();
    throw new Error(`Failed to create OSF component: ${osfResult.status}`);
  }

  const nodeData = await osfResult.json();

  if (nodeData.errors) {
    throw new Error(nodeData.errors[0]?.detail || 'OSF API error');
  }

  const filesLink = nodeData.data.relationships.files.links.related.href;

  const filesResult = await fetch(filesLink, {
    method: "GET",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${osfToken}`,
    },
  });

  if (!filesResult.ok) {
    const errorText = await filesResult.text();
    throw new Error(`Failed to get OSF upload link: ${filesResult.status}`);
  }

  const filesData = await filesResult.json();
  const uploadLink = filesData.data[0].links.upload;

  return {
    componentId: nodeData.data.id,
    uploadLink: uploadLink,
    osfRepo: osfRepo
  };
}

export async function createExperimentDocument(experimentData) {
  const {
    id,
    title,
    osfRepo,
    osfComponent,
    osfFilesLink,
    owner,
    nConditions = 1,
    useValidation = true,
    allowJSON = true,
    allowCSV = true,
    limitSessions = false,
    maxSessions = 1
  } = experimentData;

  const batch = writeBatch(db);

  const experimentDoc = doc(db, "experiments", id);
  batch.set(experimentDoc, {
    title: title,
    osfRepo: osfRepo,
    osfComponent: osfComponent,
    osfFilesLink: osfFilesLink,
    active: false,
    activeBase64: false,
    activeConditionAssignment: false,
    sessions: 0,
    limitSessions: limitSessions,
    maxSessions: maxSessions,
    id: id,
    owner: owner,
    nConditions: nConditions,
    currentCondition: 0,
    useValidation: useValidation,
    allowJSON: allowJSON,
    allowCSV: allowCSV,
    requiredFields: ["trial_type"],
  });

  const userDoc = doc(db, `users/${owner}`);
  batch.update(userDoc, {
    experiments: arrayUnion(id),
  });

  await batch.commit();

  return id;
}

// Non-OSF providers (gdrive, and later figshare/dataverse) are created
// server-side via /api/createexperiment (see functions/src/create-experiment.ts)
// rather than the browser-driven OSF path above -- the server needs the
// decrypted provider token that only resolve-token.ts can produce. This
// helper just calls that endpoint and normalizes the response shape to
// match createExperiment()'s { experimentId } contract.
export async function createProviderExperiment(provider, title, parentFolderId, researcherInput) {
  const user = auth.currentUser;
  if (!user) {
    throw new Error("User not authenticated");
  }

  const idToken = await user.getIdToken();

  const response = await fetch("/api/createexperiment", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      provider,
      title,
      uid: user.uid,
      idToken,
      ...(parentFolderId ? { parentFolderId } : {}),
      ...(researcherInput && Object.keys(researcherInput).length > 0
        ? { researcherInput }
        : {}),
    }),
  });

  const data = await response.json();

  if (!response.ok) {
    throw new Error(data.error || `Failed to create experiment: ${response.status}`);
  }

  return {
    experimentId: data.experimentID,
  };
}

export async function createExperiment(params) {
  const {
    title,
    osfRepo,
    osfComponentName,
    region = 'us',
    uid,
    nConditions = 1,
    useValidation = true,
    allowJSON = true,
    allowCSV = true,
    useSessionLimit = false,
    maxSessions = 1
  } = params;

  // Generate experiment ID
  const nanoid = customAlphabet(
    "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz",
    12
  );
  const id = nanoid();

  // Get current user
  const user = auth.currentUser;
  if (!user) {
    throw new Error('User not authenticated');
  }

  // Get OSF token
  const osfToken = await getUserOsfToken(user);
  if (!osfToken) {
    throw new Error('No valid OSF token found');
  }

  // Create OSF child component
  const osfData = await createOsfChildComponent(osfToken, osfRepo, osfComponentName, region);

  // Create experiment document
  const experimentId = await createExperimentDocument({
    id: id,
    title: title,
    osfRepo: osfData.osfRepo,
    osfComponent: osfData.componentId,
    osfFilesLink: osfData.uploadLink,
    owner: uid,
    nConditions: nConditions,
    useValidation: useValidation,
    allowJSON: allowJSON,
    allowCSV: allowCSV,
    limitSessions: useSessionLimit,
    maxSessions: maxSessions
  });

  return {
    experimentId: experimentId,
    title: title,
    osfComponent: osfData.componentId,
    osfProject: osfData.osfRepo
  };
}